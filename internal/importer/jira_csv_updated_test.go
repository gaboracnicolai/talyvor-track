// ─── the four outcomes ─────────────────────────────────────────────────────
func TestJiraCSVUpdated_TheFourOutcomes(t *testing.T) {
	t.Run("a value the layouts accept lands and says nothing", func(t *testing.T) {
		ci, row := buildIndex([]string{"Summary", "Updated"}), []string{"a", "03/Mar/2025 9:09 AM"}
		got, notes := jiraCSVUpdated(ci, row)
		if len(notes) != 0 {
			t.Errorf("notes = %+v, want none", notes)
		}
		if want := time.Date(2025, 3, 3, 9, 9, 0, 0, time.UTC); !got.Equal(want) {
			t.Errorf("got %s, want %s", got, want)
		}
	})

	t.Run("no Updated column at all is its own report", func(t *testing.T) {
		ci, row := buildIndex([]string{"Summary", "Status"}), []string{"a", "Open"}
		got, notes := jiraCSVUpdated(ci, row)
		if !got.IsZero() {
			t.Errorf("got %s, want the zero time", got)
		}
		if len(notes) != 1 || notes[0].Via != viaNoUpdatedColumn {
			t.Fatalf("notes = %+v, want exactly one %s", notes, viaNoUpdatedColumn)
		}
	})

	t.Run("an empty cell under a present header is a different report", func(t *testing.T) {
		ci, row := buildIndex([]string{"Summary", "Updated"}), []string{"a", ""}
		_, notes := jiraCSVUpdated(ci, row)
		if len(notes) != 1 || notes[0].Via != viaNoUpdatedValue {
			t.Fatalf("notes = %+v, want exactly one %s", notes, viaNoUpdatedValue)
		}
	})

	t.Run("a shape no pinned layout accepts is REPORTED, never defaulted", func(t *testing.T) {
		ci, row := buildIndex([]string{"Summary", "Updated"}), []string{"a", "2025-03-03T09:09:00Z"}
		got, notes := jiraCSVUpdated(ci, row)
		if !got.IsZero() {
			t.Errorf("got %s, want the zero time — an unparseable value must not become a guess", got)
		}
		if len(notes) != 1 || notes[0].Via != viaUnparseableDate {
			t.Fatalf("notes = %+v, want exactly one %s", notes, viaUnparseableDate)
		}
		if notes[0].Value != "2025-03-03T09:09:00Z" {
			t.Errorf("the note drops the provider's value; got %q", notes[0].Value)
		}
	})
}

// TestJiraCSVUpdated_TheTwoAbsencesRenderDifferently — the whole reason the two Via constants are
// kept apart. If they rendered the same sentence an operator could not tell "this export has no
// Updated column" from "these rows had empty cells", and #73's structural-zero defence would be
// decoration.
func TestJiraCSVUpdated_TheTwoAbsencesRenderDifferently(t *testing.T) {
	noColumn := FieldNote{Field: fieldUpdated, Via: viaNoUpdatedColumn}.render(3)
	noValue := FieldNote{Field: fieldUpdated, Via: viaNoUpdatedValue}.render(3)
	if noColumn == noValue {
		t.Fatalf("both absences render the same sentence: %q", noColumn)
	}
	for _, s := range []string{noColumn, noValue} {
		if strings.TrimSpace(s) == "" {
			t.Fatalf("an absence rendered as the empty string — it would vanish from the report")
		}
	}
	// The no-column sentence must name the column, so the operator knows what to re-export.
	if !strings.Contains(noColumn, jiraCSVUpdatedColumn) {
		t.Errorf("the no-column sentence does not name %q: %q", jiraCSVUpdatedColumn, noColumn)
	}
}
